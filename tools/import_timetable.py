"""Extract a school timetable into a separate, normalized H2 source database.

Requires openpyxl, Java and an H2 driver (available through the project's Maven
dependencies). Does not change the application database or the source workbook.
"""
import argparse
from collections import Counter
import csv
from datetime import datetime
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

import openpyxl


SCHEMA = """
CREATE TABLE timetable_imports (
 id INT PRIMARY KEY, source_name VARCHAR NOT NULL, sha256 CHAR(64) NOT NULL,
 title VARCHAR, snapshot_date DATE, imported_at TIMESTAMP NOT NULL);
CREATE TABLE timetable_source_rows (
 id INT PRIMARY KEY, import_id INT NOT NULL REFERENCES timetable_imports(id),
 sheet_name VARCHAR NOT NULL, row_number INT NOT NULL, data_json CLOB NOT NULL,
 UNIQUE(import_id, sheet_name, row_number));
CREATE TABLE timetable_departments (code VARCHAR PRIMARY KEY);
CREATE TABLE timetable_semesters (
 code VARCHAR PRIMARY KEY, starts_at DATE, ends_at DATE,
 registration_open_at TIMESTAMP, registration_close_at TIMESTAMP);
CREATE TABLE timetable_courses (
 code VARCHAR PRIMARY KEY, department_code VARCHAR NOT NULL REFERENCES timetable_departments(code),
 name VARCHAR NOT NULL, english_name VARCHAR, workload VARCHAR NOT NULL,
 credits INT NOT NULL CHECK(credits >= 0));
CREATE TABLE timetable_sections (
 id VARCHAR PRIMARY KEY, semester_code VARCHAR NOT NULL REFERENCES timetable_semesters(code),
 section_code VARCHAR NOT NULL, course_code VARCHAR NOT NULL REFERENCES timetable_courses(code),
 capacity INT NOT NULL CHECK(capacity > 0), enrolled_snapshot INT CHECK(enrolled_snapshot >= 0),
 source_status VARCHAR NOT NULL, section_type VARCHAR, opening_round VARCHAR,
 management_code VARCHAR, teaching_type VARCHAR, notes VARCHAR,
 required_lab_raw VARCHAR, attention VARCHAR, minimum_capacity INT,
 UNIQUE(semester_code, section_code));
CREATE TABLE timetable_section_links (
 section_id VARCHAR PRIMARY KEY REFERENCES timetable_sections(id),
 linked_section_id VARCHAR NOT NULL REFERENCES timetable_sections(id));
CREATE TABLE timetable_rooms (code VARCHAR PRIMARY KEY);
CREATE TABLE timetable_meetings (
 id INT PRIMARY KEY, source_row_id INT NOT NULL UNIQUE REFERENCES timetable_source_rows(id),
 section_id VARCHAR NOT NULL REFERENCES timetable_sections(id), session_number VARCHAR,
 day_of_week INT CHECK(day_of_week BETWEEN 1 AND 7), starts_at TIME, ends_at TIME, time_raw VARCHAR,
 start_period INT, end_period INT, shift VARCHAR, weeks_raw VARCHAR,
 room_code VARCHAR REFERENCES timetable_rooms(code),
 CHECK(starts_at IS NULL OR ends_at IS NULL OR starts_at < ends_at));
CREATE TABLE timetable_meeting_weeks (
 meeting_id INT REFERENCES timetable_meetings(id), week_number INT CHECK(week_number > 0),
 PRIMARY KEY(meeting_id, week_number));
CREATE TABLE timetable_import_issues (
 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_row_id INT REFERENCES timetable_source_rows(id),
 issue_code VARCHAR NOT NULL, details VARCHAR NOT NULL);
CREATE INDEX idx_timetable_section_course ON timetable_sections(course_code);
CREATE INDEX idx_timetable_meeting_section ON timetable_meetings(section_id);
CREATE INDEX idx_timetable_meeting_room ON timetable_meetings(room_code, day_of_week);
"""


def clean(value):
    if value is None:
        return None
    text = str(value).strip()
    return None if not text or text.upper() == "NULL" else text


def integer(value):
    text = clean(value)
    if text is None:
        return None
    if not re.fullmatch(r"\d+(?:\.0+)?", text):
        raise ValueError(f"Expected a nonnegative integer, got {value!r}")
    return int(float(text))


def sql_value(value):
    if value is None:
        return "NULL"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def parse_weeks(raw):
    if not raw:
        return []
    if not re.fullmatch(r"\d+(?:-\d+)?(?:\s*,\s*\d+(?:-\d+)?)*", raw):
        return None
    result = set()
    for part in raw.split(","):
        bounds = [int(x) for x in part.strip().split("-")]
        first, last = bounds[0], bounds[-1]
        if first < 1 or first > last or last > 100:
            return None
        result.update(range(first, last + 1))
    return sorted(result)


def time_pair(raw):
    if raw is None:
        return None, None
    if not re.fullmatch(r"\d{4}-\d{4}", raw):
        raise ValueError(f"Invalid time range: {raw}")
    first, last = raw.split("-")
    start = datetime.strptime(first, "%H%M").strftime("%H:%M:%S")
    end = datetime.strptime(last, "%H%M").strftime("%H:%M:%S")
    if start >= end:
        raise ValueError(f"Time range does not increase: {raw}")
    return start, end


def verify_database(java, jar, jdbc_url, raw_rows, expected):
    """Compare saved table counts and every raw cell with the extracted source."""
    with tempfile.TemporaryDirectory(prefix="coursebot-timetable-check-") as directory:
        csv_path = Path(directory) / "source.csv"
        queries = [f"SELECT '{key}=' || COUNT(*) FROM {table};" for key, table in (
            ("courses", "timetable_courses"), ("sections", "timetable_sections"),
            ("meetings", "timetable_meetings"), ("rooms", "timetable_rooms"),
            ("departments", "timetable_departments"), ("meeting_weeks", "timetable_meeting_weeks"),
            ("source_rows", "timetable_source_rows"))]
        queries += [
            "SELECT 'unmatched_source_rows=' || COUNT(*) FROM timetable_source_rows r "
            "LEFT JOIN timetable_meetings m ON m.source_row_id=r.id "
            "WHERE r.sheet_name='Sheet1' AND r.row_number>=4 AND m.id IS NULL;",
            "CALL CSVWRITE(" + sql_value(csv_path.as_posix()) + ", "
            "'SELECT sheet_name,row_number,data_json FROM timetable_source_rows ORDER BY id');"]
        check = subprocess.run([java, "-cp", str(jar), "org.h2.tools.Shell", "-url", jdbc_url,
                                "-user", "sa", "-sql", " ".join(queries)],
                               check=True, capture_output=True, text=True)
        if "Error" in check.stdout or "Exception" in check.stdout:
            raise RuntimeError(check.stdout)
        for key in ("courses", "sections", "meetings", "rooms", "departments", "meeting_weeks", "source_rows"):
            if not re.search(rf"(?m)^{key}={expected[key]}\s*$", check.stdout):
                raise AssertionError(f"Persisted count mismatch: {key}\n{check.stdout}")
        if not re.search(r"(?m)^unmatched_source_rows=0\s*$", check.stdout):
            raise AssertionError("Some timetable source rows have no normalized meeting")
        with csv_path.open(encoding="utf-8", newline="") as stream:
            saved_rows = [(r["SHEET_NAME"], int(r["ROW_NUMBER"]), json.loads(r["DATA_JSON"]))
                          for r in csv.DictReader(stream)]
        if saved_rows != raw_rows:
            raise AssertionError("Saved raw source cells differ from the workbook")
    return check.stdout + f"All {len(raw_rows)} nonempty source rows round-trip exactly.\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--h2-jar", type=Path)
    args = parser.parse_args()
    source = args.source.resolve()
    source_match = re.fullmatch(r"TKB(\d+)-FULL", source.stem, re.IGNORECASE)
    if not source_match:
        raise SystemExit("Expected source filename TKB<semester>-FULL.xlsx")
    semester_code = source_match[1]
    output = (args.output or Path("data/imports") / ("tkb" + semester_code)).resolve()
    database = output / ("timetable-" + semester_code)
    if database.with_suffix(".mv.db").exists():
        raise SystemExit("Database already exists. Choose a new --output directory.")
    jars = sorted((Path.home() / ".m2/repository/com/h2database/h2").glob("*/*.jar"))
    jar = args.h2_jar or (jars[-1] if jars else None)
    java = shutil.which("java")
    if not java or jar is None or not jar.is_file():
        raise SystemExit("Java and the H2 driver are required. Supply --h2-jar if necessary.")

    workbook = openpyxl.load_workbook(source, read_only=True, data_only=False)
    sheet = workbook["Sheet1"]
    headers = list(next(sheet.iter_rows(min_row=3, max_row=3, values_only=True)))
    expected = ["Kỳ", "Trường_Viện_Khoa", "Mã_lớp", "Mã_lớp_kèm", "Mã_HP", "Tên_HP",
                "Tên_HP_Tiếng_Anh", "Khối_lượng", "Ghi_chú", "Buổi_số", "Thứ",
                "Thời_gian", "BĐ", "KT", "Kíp", "Tuần", "Phòng", "Cần_TN", "SLĐK",
                "SL_Max", "Trạng_thái", "Loại_lớp", "Đợt_mở", "Mã_QL", "TeachingType", "Chú ý"]
    if len(headers) != len(set(headers)) or set(headers) - set(expected) - {"SL_Min"} or set(expected) - set(headers) - {"Chú ý"}:
        raise ValueError("Workbook headers differ from the supported school export.")
    column_indices = {name: index for index, name in enumerate(headers)}
    title = clean(sheet.cell(1, 1).value)
    match = re.search(r"(\d{2}\.\d{2}\.\d{4})", title or "")
    snapshot_date = datetime.strptime(match[1], "%d.%m.%Y").date().isoformat() if match else None
    statements = [SCHEMA, "SET AUTOCOMMIT FALSE;"]
    counts = Counter()

    def insert(table, values):
        statements.append(f"INSERT INTO {table} VALUES ({','.join(sql_value(v) for v in values)});")

    def issue(row_id, code, details):
        statements.append("INSERT INTO timetable_import_issues(source_row_id,issue_code,details) VALUES ("
                          + ",".join(sql_value(v) for v in (row_id, code, details)) + ");")
        counts[code] += 1

    insert("timetable_imports", [1, source.name, hashlib.sha256(source.read_bytes()).hexdigest(),
                               title, snapshot_date, datetime.now().isoformat(sep=" ", timespec="seconds")])
    data, raw_rows = [], []
    raw_id = 0
    for current in workbook:
        for row_number, values in enumerate(current.iter_rows(values_only=True), 1):
            if not any(v is not None for v in values):
                continue
            raw_id += 1
            raw_rows.append((current.title, row_number, json.loads(json.dumps(values, ensure_ascii=False, default=str))))
            insert("timetable_source_rows", [raw_id, 1, current.title, row_number,
                                             json.dumps(values, ensure_ascii=False, default=str)])
            if current.title == "Sheet1" and row_number >= 4:
                normalized = [clean(values[column_indices[name]]) if name in column_indices else None for name in expected]
                normalized.append(clean(values[column_indices["SL_Min"]]) if "SL_Min" in column_indices else None)
                data.append((raw_id, row_number, normalized))
    workbook.close()

    courses, sections = {}, {}
    departments, semesters, rooms = set(), set(), set()
    for source_id, row_number, row in data:
        if any(row[i] is None for i in (0, 1, 2, 4, 5, 7, 19, 20)):
            raise ValueError(f"Required source field missing at row {row_number}")
        departments.add(row[1])
        semesters.add(row[0])
        if row[0] != semester_code:
            raise ValueError(f"Semester differs from source filename at row {row_number}: {row[0]}")
        if row[16]:
            rooms.add(row[16])
        credit_match = re.fullmatch(r"(\d+)\(.*\)", row[7])
        if not credit_match:
            raise ValueError(f"Cannot read credits at row {row_number}: {row[7]}")
        course = (row[4], row[1], row[5], row[6], row[7], int(credit_match[1]))
        if row[4] in courses and courses[row[4]] != course:
            raise ValueError(f"Conflicting course metadata: {row[4]} (row {row_number})")
        if row[4] not in courses and course[-1] == 0:
            issue(source_id, "ZERO_CREDITS", f"Môn {row[4]} ghi 0 tín chỉ trong nguồn; giữ nguyên.")
        courses[row[4]] = course
        section_id = row[0] + ":" + row[2]
        section = (section_id, row[0], row[2], row[4], integer(row[19]), integer(row[18]),
                   row[20], row[21], row[22], row[23], row[24], row[8], row[17], row[25], integer(row[26]))
        if section[4] <= 0:
            raise ValueError(f"Invalid capacity at row {row_number}")
        if section_id in sections:
            if sections[section_id][0] != section or sections[section_id][1] != row[3]:
                raise ValueError(f"Conflicting section metadata: {section_id}")
        else:
            sections[section_id] = (section, row[3])
            if section[5] is None:
                issue(source_id, "UNKNOWN_ENROLLED", "Nguồn thiếu SLĐK; giữ NULL, không thay bằng 0.")
            elif section[5] > section[4]:
                issue(source_id, "ENROLLED_EXCEEDS_CAPACITY", f"Lớp {row[2]}: SLĐK={section[5]}, SL_Max={section[4]}.")

    for code in sorted(departments):
        insert("timetable_departments", [code])
    for code in sorted(semesters):
        insert("timetable_semesters", [code, None, None, None, None])
    for code in sorted(courses):
        insert("timetable_courses", courses[code])
    for code in sorted(sections):
        insert("timetable_sections", sections[code][0])
    for code, (_, companion) in sorted(sections.items()):
        if companion:
            target = code.split(":", 1)[0] + ":" + companion
            if target not in sections:
                raise ValueError(f"Linked section not found: {target}")
            insert("timetable_section_links", [code, target])
    for code in sorted(rooms):
        insert("timetable_rooms", [code])

    week_count = 0
    for meeting_id, (source_id, row_number, row) in enumerate(data, 1):
        try:
            start, end = time_pair(row[11])
        except ValueError as error:
            start, end = None, None
            issue(source_id, "INVALID_TIME", f"Dòng {row_number}: {error}; giữ time_raw, chưa tạo giờ chuẩn hóa.")
        weekday = integer(row[10])
        if weekday is not None and not 2 <= weekday <= 8:
            raise ValueError(f"Invalid school weekday at row {row_number}: {weekday}")
        insert("timetable_meetings", [meeting_id, source_id, row[0] + ":" + row[2], row[9],
                                      weekday - 1 if weekday else None, start, end, row[11],
                                      integer(row[12]), integer(row[13]), row[14], row[15], row[16]])
        if weekday is None or start is None or row[15] is None:
            issue(source_id, "MISSING_SCHEDULE", f"Dòng {row_number} chưa có đầy đủ thứ, giờ hoặc tuần học.")
        if row[16] is None:
            issue(source_id, "MISSING_ROOM", f"Dòng {row_number} chưa có phòng học.")
        weeks = parse_weeks(row[15])
        if weeks is None:
            issue(source_id, "AMBIGUOUS_WEEKS", f"Tuần={row[15]!r}; giữ nguyên, chưa suy diễn dấu chấm thành dấu phẩy.")
        else:
            for week in weeks:
                insert("timetable_meeting_weeks", [meeting_id, week])
                week_count += 1
    statements.append("COMMIT;")
    summary = {"source": str(source), "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
               "snapshot_date": snapshot_date, "source_rows": raw_id, "timetable_rows": len(data),
               "semesters": len(semesters), "departments": len(departments), "courses": len(courses),
               "sections": len(sections), "meetings": len(data), "rooms": len(rooms),
               "meeting_weeks": week_count, "issues": dict(counts),
               "section_statuses": dict(Counter(value[0][6] for value in sections.values())),
               "missing_information": ["Giảng viên", "Ngày bắt đầu/kết thúc học kỳ", "Thời gian mở/đóng đăng ký",
                                       "Danh tính sinh viên đã đăng ký", "Khung chương trình và môn tiên quyết"]}
    output.mkdir(parents=True, exist_ok=True)
    sql_path = output / ("timetable-" + semester_code + ".sql")
    sql_path.write_text("\n".join(statements), encoding="utf-8")
    jdbc_url = "jdbc:h2:file:" + database.as_posix()
    subprocess.run([java, "-cp", str(jar), "org.h2.tools.RunScript", "-url", jdbc_url,
                    "-user", "sa", "-script", str(sql_path)], check=True)
    verification = verify_database(java, jar, jdbc_url, raw_rows, summary)
    (output / "verification.txt").write_text(verification, encoding="utf-8")
    (output / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    print(verification)


if __name__ == "__main__":
    main()
